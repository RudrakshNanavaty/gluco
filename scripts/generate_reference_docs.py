"""Generate source-linked Markdown reference pages without extra dependencies."""

from __future__ import annotations

import argparse
import ast
import re
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "reference"
GENERATED_NOTICE = "<!-- Generated by scripts/generate_reference_docs.py; do not edit. -->"
HTTP_METHODS = {"get", "post", "put", "patch", "delete"}


@dataclass(frozen=True)
class Symbol:
    kind: str
    name: str
    signature: str
    summary: str
    source: str
    line: int


def summary(docstring: str | None) -> str:
    if not docstring:
        return "No public description is available yet."
    paragraph = docstring.strip().split("\n\n", 1)[0]
    return " ".join(line.strip() for line in paragraph.splitlines())


def expression_name(node: ast.expr | None) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        prefix = expression_name(node.value)
        return f"{prefix}.{node.attr}" if prefix else node.attr
    if isinstance(node, ast.Subscript):
        return expression_name(node.value)
    if isinstance(node, ast.Constant):
        return repr(node.value)
    return "value"


def python_signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    arguments: list[str] = []
    all_positional = [*node.args.posonlyargs, *node.args.args]
    defaults = [None] * (len(all_positional) - len(node.args.defaults)) + list(
        node.args.defaults
    )
    for arg, default in zip(all_positional, defaults, strict=True):
        rendered = arg.arg
        if arg.annotation:
            rendered += f": {expression_name(arg.annotation)}"
        if default is not None:
            rendered += " = ..."
        arguments.append(rendered)
    if node.args.vararg:
        arguments.append(f"*{node.args.vararg.arg}")
    for arg, default in zip(node.args.kwonlyargs, node.args.kw_defaults, strict=True):
        rendered = arg.arg
        if arg.annotation:
            rendered += f": {expression_name(arg.annotation)}"
        if default is not None:
            rendered += " = ..."
        arguments.append(rendered)
    if node.args.kwarg:
        arguments.append(f"**{node.args.kwarg.arg}")
    result = f"{node.name}({', '.join(arguments)})"
    if node.returns:
        result += f" -> {expression_name(node.returns)}"
    return result


def public_python_symbols(path: Path) -> list[Symbol]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    relative = path.relative_to(ROOT).as_posix()
    symbols: list[Symbol] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            symbols.append(
                Symbol("class", node.name, node.name, summary(ast.get_docstring(node)), relative, node.lineno)
            )
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            symbols.append(
                Symbol(
                    "function",
                    node.name,
                    python_signature(node),
                    summary(ast.get_docstring(node)),
                    relative,
                    node.lineno,
                )
            )
    return symbols


def route_entries(path: Path) -> list[tuple[str, str, str, int, str]]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    relative = path.relative_to(ROOT).as_posix()
    routes: list[tuple[str, str, str, int, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for decorator in node.decorator_list:
            if not isinstance(decorator, ast.Call) or not isinstance(decorator.func, ast.Attribute):
                continue
            method = decorator.func.attr.lower()
            if method not in HTTP_METHODS or not decorator.args:
                continue
            route = decorator.args[0]
            if not isinstance(route, ast.Constant) or not isinstance(route.value, str):
                continue
            routes.append(
                (method.upper(), route.value, node.name, node.lineno, summary(ast.get_docstring(node)))
            )
    return [(method, route, name, line, relative + "|" + description) for method, route, name, line, description in routes]


EXPORT_PATTERN = re.compile(
    r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|class|const|type|interface|enum)\s+([A-Za-z_$][\w$]*)",
    re.MULTILINE,
)


def frontend_exports(path: Path) -> list[Symbol]:
    text = path.read_text(encoding="utf-8")
    relative = path.relative_to(ROOT).as_posix()
    symbols: list[Symbol] = []
    for match in EXPORT_PATTERN.finditer(text):
        line = text.count("\n", 0, match.start()) + 1
        declaration = text[match.start() : text.find("\n", match.start())].strip()
        symbols.append(
            Symbol(
                "export",
                match.group(1),
                declaration,
                "Public TypeScript/React export. Follow the source link for its implementation and usage.",
                relative,
                line,
            )
        )
    return symbols


def source_link(symbol: Symbol) -> str:
    return f"../../{symbol.source}#L{symbol.line}"


def render_symbols(title: str, introduction: str, symbols: list[Symbol]) -> str:
    lines = [GENERATED_NOTICE, "", f"# {title}", "", introduction, ""]
    grouped: dict[str, list[Symbol]] = {}
    for symbol in symbols:
        grouped.setdefault(symbol.source, []).append(symbol)
    for source in sorted(grouped):
        lines.extend([f"## `{source}`", ""])
        for symbol in sorted(grouped[source], key=lambda item: item.line):
            lines.extend(
                [
                    f"### {symbol.kind.title()}: `{symbol.name}`",
                    "",
                    f"`{symbol.signature}`",
                    "",
                    symbol.summary,
                    "",
                    f"[View source]({source_link(symbol)})",
                    "",
                ]
            )
    return "\n".join(lines).rstrip() + "\n"


def build_documents() -> dict[Path, str]:
    backend_files = sorted((ROOT / "back-end" / "src" / "agent").rglob("*.py"))
    backend_symbols = [symbol for path in backend_files for symbol in public_python_symbols(path)]
    routes = [route for path in backend_files for route in route_entries(path)]

    route_lines = [
        GENERATED_NOTICE,
        "",
        "# HTTP API reference",
        "",
        "Generated from FastAPI route decorators. Authentication and role constraints are explained in the [back-end guide](../../back-end/README.md).",
        "",
        "| Method | Path | Handler | Description | Source |",
        "|---|---|---|---|---|",
    ]
    for method, route, name, line, packed in sorted(routes, key=lambda item: (item[1], item[0])):
        source, description = packed.split("|", 1)
        route_lines.append(
            f"| `{method}` | `{route or '/'}` | `{name}` | {description} | [source](../../{source}#L{line}) |"
        )

    frontend_files = sorted((ROOT / "front-end" / "src").rglob("*.ts")) + sorted(
        (ROOT / "front-end" / "src").rglob("*.tsx")
    )
    frontend_symbols = [symbol for path in frontend_files for symbol in frontend_exports(path)]

    index = f"""{GENERATED_NOTICE}

# Generated reference

These pages are regenerated from source by `scripts/generate_reference_docs.py`.
CI fails when the checked-in reference is stale.

- [HTTP API](http-api.md) - FastAPI methods, paths, handlers, and source links
- [Back-end symbols](back-end.md) - public Python classes and functions
- [Front-end exports](front-end.md) - exported TypeScript and React symbols

For worked examples, start with the [installation guide](../../INSTALL.md),
[back-end guide](../../back-end/README.md), and [front-end guide](../../front-end/README.md).

## Coverage

- **{len(routes)}** HTTP route declarations
- **{len(backend_symbols)}** public back-end symbols
- **{len(frontend_symbols)}** public front-end exports
"""
    return {
        OUTPUT / "README.md": index,
        OUTPUT / "http-api.md": "\n".join(route_lines).rstrip() + "\n",
        OUTPUT / "back-end.md": render_symbols(
            "Back-end symbol reference",
            "Public classes and functions generated from Python source and docstrings.",
            backend_symbols,
        ),
        OUTPUT / "front-end.md": render_symbols(
            "Front-end export reference",
            "Public exports generated from TypeScript and React source declarations.",
            frontend_symbols,
        ),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    documents = build_documents()
    stale: list[str] = []
    for path, content in documents.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Generated reference is stale: " + ", ".join(stale))
        print("Run: python scripts/generate_reference_docs.py")
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(documents)} reference pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
